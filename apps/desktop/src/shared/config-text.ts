/**
 * Pure helpers for device configuration text, shared by main (backup dedupe) and the renderer
 * (diff viewer): the noise filter and stanza structure.
 */

/** Lines that change on every capture without a configuration change. */
const NOISE: readonly RegExp[] = [
  /^!\s*Last configuration change at\b/i,
  /^!!\s*Last configuration change at\b/i,
  /^!\s*NVRAM config last updated at\b/i,
  /^!\s*No configuration change since last restart/i,
  /^Building configuration\.\.\./,
  /^Current configuration\s*:\s*\d+\s*bytes/i,
  /^Current configuration:\s*$/i,
  // NX-OS header
  /^!\s*Time:/,
  /^!\s*Running configuration last done at:/i,
  // IOS-XR and NX-OS print the clock before the config.
  /^(?:Mon|Tue|Wed|Thu|Fri|Sat|Sun)\s+(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+\d{1,2}\s+\d{2}:\d{2}:\d{2}(?:\.\d+)?\s+\S+$/,
  /^ntp clock-period\b/,
  // Junos
  /^##\s*Last (?:commit|changed):/i,
  // Huawei VRP
  /^!\s*Last configuration was (?:updated|saved) at\b/i,
  // ASA
  /^Cryptochecksum:/,
  /^:\s*Written by\b.*\bat\b/i,
  // FortiOS file header counters
  /^#conf_file_ver=/,
  // Uptime counters in comments or banners generated by the device
  /^[!#:]+.*\buptime\b/i,
  /\buptime is\b/i
]

/** Hex lines of a certificate blob (`crypto pki certificate chain` … `quit`). */
const CERT_HEX = /^\s*(?:[0-9A-Fa-f]{2,8}\s*){1,16}$/
const CERT_START = /^\s*certificate\s+(?:ca\s+|self-signed\s+|rollover\s+)?\S+/i

const splitLines = (text: string): string[] => text.replace(/\r\n?/g, '\n').split('\n')

/** For each line, whether it is noise (changes without a configuration change). */
export function noiseMask(lines: readonly string[]): boolean[] {
  const mask: boolean[] = new Array(lines.length).fill(false)
  let inCert = false
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!
    const t = line.trim()
    if (inCert) {
      if (/^quit$/i.test(t)) {
        mask[i] = true
        inCert = false
        continue
      }
      if (CERT_HEX.test(line) && t) {
        mask[i] = true
        continue
      }
      inCert = false
    }
    if (CERT_START.test(line) && /^\s/.test(line)) {
      // Keep the `certificate <serial>` line (a new certificate is a real change); drop its body.
      inCert = true
      continue
    }
    if (NOISE.some((re) => re.test(t))) mask[i] = true
  }
  return mask
}

/** The text without noise lines. */
export function stripNoise(text: string): string {
  const lines = splitLines(text)
  const mask = noiseMask(lines)
  return lines.filter((_, i) => !mask[i]).join('\n')
}

/** What a backup is compared by: noise removed, trailing whitespace and blank runs collapsed. */
export function normalizeConfig(text: string): string {
  return stripNoise(text)
    .split('\n')
    .map((l) => l.replace(/\s+$/, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

// ------------------------------------------------------------------ stanzas

/**
 * - `indent`: IOS-style, children indented under their parent (`interface Gi1/0/1`, ` ip address …`)
 * - `braces`: Junos/PAN-OS curly hierarchy (`interfaces {`, `}`)
 * - `set`: one statement per line (`set interfaces ge-0/0/0 unit 0 …`, Junos `display set`)
 * - `fortios`: `config …` / `edit …` / `next` / `end` blocks
 */
export type StanzaStyle = 'indent' | 'braces' | 'set' | 'fortios'

export function stanzaStyle(text: string, platform?: string): StanzaStyle {
  if (platform === 'fortios') return 'fortios'
  const lines = splitLines(text).slice(0, 400)
  const set = lines.filter((l) => /^(?:set|delete|deactivate)\s/.test(l)).length
  const brace = lines.filter((l) => /\{\s*$/.test(l)).length
  const forti = lines.filter((l) => /^config\s/.test(l)).length
  const nonEmpty = lines.filter((l) => l.trim()).length || 1
  if (forti > 0 && lines.some((l) => /^\s+edit\s/.test(l))) return 'fortios'
  if (set / nonEmpty > 0.5) return 'set'
  if (brace > 2 && (platform === 'junos' || platform === 'panos' || brace / nonEmpty > 0.05)) return 'braces'
  return 'indent'
}

export interface Stanza {
  /** 0-based line of the header. */
  start: number
  /** 0-based last line that belongs to it (inclusive). */
  end: number
  header: string
}

const SEPARATOR = /^\s*[!#]\s*$|^\s*$/
const indentOf = (l: string) => /^\s*/.exec(l)![0].replace(/\t/g, '    ').length

/**
 * The stanza path of every line: the header lines it sits under (outermost first), not counting
 * the line itself. A top-level line has an empty path.
 */
export function stanzaPaths(lines: readonly string[], style: StanzaStyle): string[][] {
  const out: string[][] = []
  if (style === 'set') {
    for (const l of lines) {
      const w = l.trim().split(/\s+/)
      if (!/^(?:set|delete|deactivate|activate)$/.test(w[0] ?? '') || w.length < 4) {
        out.push([])
        continue
      }
      // `set interfaces ge-0/0/0 unit 0 …` → "interfaces ge-0/0/0"; three words for sections whose
      // second word is a container (`protocols bgp group X`, `policy-options policy-statement X`).
      const deep = /^(?:protocols|policy-options|firewall|routing-instances|security|class-of-service|services)$/.test(w[1]!) && w.length > 4
      out.push([w.slice(1, deep ? 4 : 3).join(' ')])
    }
    return out
  }
  const stack: { indent: number; header: string }[] = []
  for (const l of lines) {
    const t = l.trim()
    if (style === 'braces') {
      out.push(stack.map((s) => s.header))
      if (/\{\s*$/.test(t)) stack.push({ indent: 0, header: t.replace(/\s*\{\s*$/, '') })
      else if (/^\}/.test(t)) stack.pop()
      continue
    }
    if (style === 'fortios') {
      if (/^(?:next|end)$/.test(t)) {
        // The closing line belongs to the block it closes.
        out.push(stack.map((s) => s.header))
        stack.pop()
        continue
      }
      out.push(stack.map((s) => s.header))
      if (/^(?:config|edit)\s/.test(t)) stack.push({ indent: 0, header: t })
      continue
    }
    // indent
    if (SEPARATOR.test(l)) {
      // `!` at column 0 closes every stanza in IOS; an indented ` !` closes only deeper ones; a blank
      // line changes nothing.
      if (/^[!#]/.test(l)) stack.length = 0
      else if (t) {
        const ind = indentOf(l)
        while (stack.length && stack.at(-1)!.indent >= ind) stack.pop()
      }
      out.push(stack.map((s) => s.header))
      continue
    }
    const ind = indentOf(l)
    while (stack.length && stack.at(-1)!.indent >= ind) stack.pop()
    out.push(stack.map((s) => s.header))
    stack.push({ indent: ind, header: t })
  }
  return out
}

/** Header ranges, for folding and sticky scroll. Only headers that have at least one child line. */
export function stanzas(lines: readonly string[], style: StanzaStyle): Stanza[] {
  const res: Stanza[] = []
  if (style === 'set') {
    const paths = stanzaPaths(lines, style)
    let cur: Stanza | null = null
    paths.forEach((p, i) => {
      const h = p[0] ?? ''
      if (cur && cur.header === h && h) cur.end = i
      else {
        if (cur && cur.end > cur.start) res.push(cur)
        cur = h ? { start: i, end: i, header: h } : null
      }
    })
    if (cur && (cur as Stanza).end > (cur as Stanza).start) res.push(cur)
    return res
  }
  const paths = stanzaPaths(lines, style)
  const open: Stanza[] = []
  for (let i = 0; i < lines.length; i++) {
    const depth = paths[i]!.length
    // Close every open stanza deeper than (or as deep as) this line's own path.
    while (open.length > depth) {
      const s = open.pop()!
      if (s.end > s.start) res.push(s)
    }
    for (const s of open) s.end = i
    const next = paths[i + 1]
    if (next && next.length > depth) open.push({ start: i, end: i, header: lines[i]!.trim().replace(/\s*\{\s*$/, '') })
  }
  for (const s of open) if (s.end > s.start) res.push(s)
  return res.sort((a, b) => a.start - b.start)
}

/** The stanza context to show for a changed line (e.g. "interface GigabitEthernet1/0/1"). */
export function contextFor(lines: readonly string[], style: StanzaStyle, line: number): string {
  const paths = stanzaPaths(lines, style)
  const p = paths[line] ?? []
  return p.join(' › ')
}
