import { join } from 'node:path'
import { axeCheck } from './support/axe'
import { expect, MOD, sizeWindow, test } from './fixtures'

test('tour visits the workspace, restores the layout, and can be skipped and replayed', async ({ hop }) => {
  const { page, app } = hop
  await page.getByRole('button', { name: 'Toggle session sidebar' }).click()
  const start = page.getByRole('region', { name: 'Get started' }).getByRole('button', { name: 'Take a tour' })
  await start.click()
  const tour = page.getByRole('dialog', { name: 'Workspace tour' })
  await expect(tour.getByRole('heading', { name: 'Find a device' })).toBeVisible()
  await expect(page.locator('#session-search')).toBeInViewport()
  await axeCheck(page, 'workspace tour')
  await sizeWindow(app, page, 900, 600)
  await tour.getByRole('button', { name: 'Next' }).click()
  await expect(tour).toContainText('Work in the terminal')
  await tour.getByRole('button', { name: 'Back' }).click()
  await expect(tour).toContainText('1 of 4')
  await tour.getByRole('button', { name: 'Next' }).click()
  await tour.getByRole('button', { name: 'Next' }).click()
  await expect(tour.getByRole('heading', { name: 'Ask the assistant' })).toBeVisible()
  await tour.getByRole('button', { name: 'Next' }).click()
  await expect(tour).toContainText('Analyze a packet capture')
  const attach = page.locator('#ai [aria-label="Attach packet capture"]')
  await expect(attach).toBeInViewport()
  const spot = page.locator('[data-tour-spotlight] > div')
  await expect.poll(async () => {
    const button = await attach.boundingBox()
    const highlight = await spot.boundingBox()
    return !!button && !!highlight && Math.abs(button.x - highlight.x - 2) < 2 && Math.abs(button.width + 4 - highlight.width) < 2
  }).toBe(true)
  if (process.env.HOPLINE_SHOTS) await page.screenshot({ animations: 'disabled', path: join(process.env.HOPLINE_SHOTS, 'tour.png') })
  await tour.getByRole('button', { name: 'Finish' }).click()
  await expect(tour).toBeHidden()
  await expect(page.getByRole('button', { name: 'Toggle session sidebar' })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('button', { name: 'Toggle assistant' })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('.xterm')).toHaveCount(0)
  await page.keyboard.press(MOD + '+K')
  const palette = page.getByRole('combobox', { name: 'Command palette' })
  await palette.fill('Take a workspace tour')
  await palette.press('Enter')
  await expect(tour).toContainText('1 of 4')
  await page.keyboard.press('Escape')
  await expect(tour).toBeHidden()
})

test('settings offer focused pages and keep drafts across a tour and immediate preferences', async ({ hop }) => {
  const { page } = hop
  const settings = page.getByRole('dialog', { name: 'Settings', exact: true })
  await page.keyboard.press(MOD + '+Comma')
  await expect(settings.getByRole('tab', { name: 'Workspace' })).toHaveAttribute('aria-selected', 'true')
  await expect(settings.getByRole('tabpanel').locator('[data-settings-hint]:visible')).toHaveCount(0)
  if (process.env.HOPLINE_SHOTS) await page.screenshot({ animations: 'disabled', path: join(process.env.HOPLINE_SHOTS, 'settings.png') })
  const motion = settings.getByRole('switch', { name: 'Reduce motion' })
  await motion.click()
  await settings.getByRole('button', { name: 'Take a tour' }).click()
  const tour = page.getByRole('dialog', { name: 'Workspace tour' })
  await expect(tour).toBeVisible()
  await tour.getByRole('button', { name: 'Skip tour' }).click()
  await expect(settings).toBeVisible()
  await expect(settings.getByRole('button', { name: 'Take a tour' })).toBeFocused()
  await expect(motion).toHaveAttribute('aria-checked', 'true')
  await settings.getByRole('tab', { name: 'Connections' }).click()
  await settings.getByLabel('Keep-alive seconds').fill('75')
  await settings.getByRole('tab', { name: 'Updates & privacy' }).click()
  const checks = settings.getByRole('switch', { name: 'Automatic checks' })
  const before = await checks.getAttribute('aria-checked')
  await checks.click()
  await expect(checks).toHaveAttribute('aria-checked', before === 'true' ? 'false' : 'true')
  await settings.getByRole('tab', { name: 'Connections' }).click()
  await expect(settings.getByLabel('Keep-alive seconds')).toHaveValue('75')
  await settings.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(settings).toBeHidden()
  const saved = await page.evaluate(() => window.hopline.settings.get())
  expect(saved).toMatchObject({ keepAliveSec: 75, reduceMotion: true, updateAutoCheck: before !== 'true' })
})
