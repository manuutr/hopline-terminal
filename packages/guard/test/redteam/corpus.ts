import type { ModeId } from '@hopline/cli-model'
import type { CommandClass, GuardPlatform } from '../../src'

/**
 * Red-team corpus for the guard. Every expectation is written by hand from the vendor research
 * (docs/research/cli-*.md §7 "Dangerous commands") and the attack classes below; none was produced
 * by running the classifier.
 *
 * - Attacks expect `blocked` or `disruptive` (never runnable by the agent).
 * - `config` marks state-changing commands that must not pass as read (they need approval).
 * - Benign reads expect exactly `read`: the guard must not get in the way of daily work.
 *
 * Control and Unicode characters are written as escapes so the file stays plain ASCII.
 */
export interface Attempt {
  p: GuardPlatform
  cmd: string
  expect: CommandClass
  /** CLI mode the line is typed in (default exec, the agent's read path). */
  mode?: ModeId
  cat: string
}

type Row = [GuardPlatform, string, CommandClass, ModeId?]
const group = (cat: string, rows: Row[]): Attempt[] => rows.map(([p, cmd, expect, mode]) => ({ p, cmd, expect, mode, cat }))

